const filesBySkill = new Map(Object.entries(LOGO_FILES).map(([skill, file]) => [skill.toLowerCase(), file]));

// The URL of a skill's logo, or null when it has none. The backend returns the vocabulary's names, but the match
// ignores case and spacing at the ends in case one is written differently.
export function skillLogoUrl(skill: string): string | null {
  const file = filesBySkill.get(skill.trim().toLowerCase());
  return file ? `${import.meta.env.BASE_URL}skill-logos/${file}.svg` : null;
}
